import { posix } from "node:path";
import type { AcceptedDifference } from "./accepted.ts";
import type { TestReference } from "./coverage.ts";
import { type CertFeature, GROUPS, LEVELS } from "./features.ts";
import { EVIDENCE, type Inventory, isScoped, type OutOfScopeRow, type ScopedRow, TABLES } from "./inventory.ts";

/** The files `renderMatrix` reads, all relative to the repository root. */
export interface MatrixInput {
  readonly inventory: Inventory;
  readonly features: readonly CertFeature[];
  readonly accepted: readonly AcceptedDifference[];
  readonly references: readonly TestReference[];
  /** The directory of the rendered document, relative to the repository root; test files are linked from there. */
  readonly directory: string;
}

/** Escapes the pipes of a cell. */
const cell = (text: string): string => text.replaceAll("|", "\\|");

/** Renders the rows of a table; the first row is the header. */
function table(rows: readonly (readonly string[])[]): string {
  const [header = [], ...body] = rows;
  const line = (cells: readonly string[]): string => `| ${cells.map(cell).join(" | ")} |`;
  return [line(header), line(header.map(() => "---")), ...body.map(line)].join("\n");
}

/** Lists the test files that name a row, as links. */
function testLinks(id: string, input: MatrixInput): string {
  const files = input.references.filter((reference) => reference.ids.includes(id)).map((reference) => reference.file);
  return [...new Set(files)]
    .sort()
    .map((file) => `[${posix.basename(file)}](${posix.relative(input.directory, file)})`)
    .join(", ");
}

function rowCells(row: ScopedRow, input: MatrixInput): string[] {
  const { id, construct, source = "", modules, evidence, unit } = row;
  return [id, construct, source, modules.join(", "), evidence.join(" "), unit, testLinks(id, input)];
}

function inventoryTables(input: MatrixInput): string {
  const header = ["Row", "Construct", "Source", "Modules", "Evidence", "Unit", "Tests"];
  const scoped = input.inventory.rows.filter(isScoped);
  const sections = TABLES.flatMap(({ letter, title }) => {
    const rows = scoped.filter((row) => row.id.startsWith(letter));
    return rows.length === 0
      ? []
      : [`### ${letter}: ${title}\n\n${table([header, ...rows.map((row) => rowCells(row, input))])}`];
  });
  return sections.join("\n\n");
}

function outOfScopeTable(input: MatrixInput): string {
  const rows = input.inventory.rows.filter((row): row is OutOfScopeRow => !isScoped(row));
  return table([
    ["Row", "Construct", "Source", "Owner"],
    ...rows.map((row) => [row.id, row.construct, row.source ?? "", row.owner]),
  ]);
}

function featureTable(input: MatrixInput): string {
  const header = ["Feature", "Name", "Levels", "Capabilities", "Owner", "Rows"];
  const groups = GROUPS.map(({ id: group, title }) => {
    const body = input.features
      .filter((feature) => feature.group === group)
      .map((feature) => [
        feature.id,
        feature.name,
        feature.levels.map((level) => LEVELS.find(({ id }) => id === level)?.title).join(", ") || "elective",
        feature.capabilities?.join(", ") ?? "",
        feature.owner ?? "",
        feature.rows?.join(", ") ?? "",
      ]);
    return `### ${title}\n\n${table([header, ...body])}`;
  });
  return groups.join("\n\n");
}

function unitTable(input: MatrixInput): string {
  const { units, merged, rows } = input.inventory;
  const body = units.map((unit) => [
    unit,
    merged.includes(unit) ? "merged" : "pending",
    String(rows.filter((row) => isScoped(row) && row.unit === unit).length),
  ]);
  return table([["Unit", "Status", "Rows"], ...body]);
}

/** The variable column of a difference in whether an item is accepted at all. */
const ACCEPTANCE = "(acceptance)";

function acceptedTable(accepted: readonly AcceptedDifference[]): string {
  if (accepted.length === 0) return "None.";
  return table([
    ["Item", "Variable", "Reason", "Source"],
    ...accepted.map((entry) => [entry.item, entry.variable || ACCEPTANCE, entry.reason, entry.source]),
  ]);
}

/** Renders `docs/conformance.md`: the evidence of every inventory row and the certification feature list. */
export function renderMatrix(input: MatrixInput): string {
  const legend = table([["Code", "Evidence"], ...EVIDENCE.map(({ code, meaning }) => [code, meaning])]);
  return `# Conformance

<!-- Generated by \`pnpm conformance:render\` from conformance/runtime-inventory.json; do not edit. -->

The runtime is not certified by 1EdTech. It implements the QTI 3.0 specifications and the companion specifications they
reference; this matrix states, for every construct, how it is evidenced. Evidence uses public material only.

The claim is scoped: items differentially tested; test sessions specification-tested. Items are compared with Longsight
qti3-core (D). No independent implementation of a QTI 3 test session was found, so the rows of test sessions carry no D and
rest on S, P and C.

## Evidence

${legend}

A test names its rows in brackets, such as \`[A79]\`. A row needs a test once its unit is merged.

## Units

${unitTable(input)}

## Certification features

The features of 1EdTech's QTI 3.0 Conformance and Certification, Appendix A, with the certification levels that
require them (CERT §2.1, §3), the capabilities for which the runtime and the player support them (CERT §2.2) and the package that
does. A feature that is not yet mapped has no capabilities, owner or rows.

${featureTable(input)}

## Inventory

${inventoryTables(input)}

## Out of scope

Constructs that the runtime leaves to the system that owns them.

${outOfScopeTable(input)}

## Accepted differences

Differences between the runtime and Longsight qti3-core that the specification settles.

${acceptedTable(input.accepted)}
`;
}
